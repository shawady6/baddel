#!/usr/bin/env node
// Generates desktop/rust/src/tables.rs from extension/shared.js so the Rust app,
// the extension and the AutoHotkey app all convert identically.
//   node scripts/gen_rust.js
const fs = require("fs");
const path = require("path");
const gen = require("./gen_ahk.js");

const file = path.join(__dirname, "..", "desktop", "rust", "src", "tables.rs");
const lit = (s) => JSON.stringify(s); // JSON escapes are valid Rust string escapes for our chars
const chr = (c) => "'" + (c === "'" ? "\\'" : c === "\\" ? "\\\\" : c) + "'";

function build() {
  const { en, ar } = gen.tables();
  const lines = ["// @generated by scripts/gen_rust.js from extension/shared.js - do not edit", ""];
  lines.push("/// Latin key -> what the same physical key types on the Arabic layout");
  lines.push("pub const EN_TO_AR: &[(char, &str)] = &[");
  for (const [k, v] of en) lines.push(`    (${chr(k)}, ${lit(v)}),`);
  lines.push("];", "");
  lines.push("/// Arabic character -> what the same physical key types on the English layout");
  lines.push("pub const AR_TO_EN: &[(char, &str)] = &[");
  for (const [k, v] of ar) lines.push(`    (${chr(k)}, ${lit(v)}),`);
  lines.push("];", "");
  return lines.join("\n");
}

if (require.main === module) {
  fs.writeFileSync(file, build(), "utf8");
  console.log("tables.rs written:", gen.tables().en.length, "en,", gen.tables().ar.length, "ar");
}
module.exports = { build, file };
